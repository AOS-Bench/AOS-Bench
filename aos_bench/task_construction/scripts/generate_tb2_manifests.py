"""Scan the cached TB-2 repo and emit one manifest per domain.

Reads each task's `task.toml` for `category`/`difficulty`/`tags`, groups them
into AOS-Bench pools (swe / ml-ds / sci), and writes per-domain manifests
under `aos_bench/task_construction/manifests/`.

Usage::

    python -m aos_bench.task_construction.scripts.generate_tb2_manifests \\
        [--cache-dir ~/.cache/aos-bench-task] \\
        [--out aos_bench/task_construction/manifests]

`arrive_wall_time`/`deadline_wall_time` are filled with simple defaults you'll
usually want to tweak: each task arrives 90 wall-clock seconds after the
previous one, with a 600-second deadline window per task.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

try:
    import tomllib  # Python 3.11+
except ModuleNotFoundError:  # pragma: no cover
    import tomli as tomllib  # type: ignore[no-redef]


_DEFAULT_CACHE = Path(
    os.environ.get(
        "AOS_TASK_CACHE",
        str(Path.home() / ".cache" / "aos-bench-task"),
    )
)


# TB-2 `category` → AOS-Bench pool. Tasks whose category isn't listed are skipped.
CATEGORY_TO_POOL: dict[str, str] = {
    "software-engineering": "swe",
    "debugging": "swe",
    "system-administration": "ops",
    "machine-learning": "ml",
    "model-training": "ml",
    "data-science": "ml",
    "data-processing": "ml",
    "scientific-computing": "sci",
    "mathematics": "sci",
    "security": "sec",
    "file-operations": "data",
    "data-querying": "data",
}

# Stream-name suffix per pool → domain bundle. We bundle a few related pools
# into one manifest because individually some are too small.
POOL_TO_BUNDLE: dict[str, str] = {
    "swe": "tb2-swe",
    "ops": "tb2-swe",        # SysAdmin folds into SWE bundle
    "ml": "tb2-ml-ds",
    "sci": "tb2-sci",
    "sec": "tb2-sec",
    "data": "tb2-data",
}


def _is_encrypted(task_dir: Path) -> bool:
    return any(p.name.endswith(".enc") for p in (task_dir / "environment").glob("*"))


def _read_task(task_dir: Path) -> dict | None:
    toml_path = task_dir / "task.toml"
    if not toml_path.exists():
        return None
    raw = tomllib.loads(toml_path.read_text())
    meta = raw.get("metadata", {})
    return {
        "task_id": task_dir.name,
        "category": meta.get("category"),
        "difficulty": meta.get("difficulty"),
        "tags": meta.get("tags", []),
        "expert_time_min": meta.get("expert_time_estimate_min", 30.0),
        "from_image": _peek_from(task_dir / "environment" / "Dockerfile"),
        "encrypted": _is_encrypted(task_dir),
    }


_FROM_RE = re.compile(r"^\s*FROM\s+(\S+)", re.MULTILINE)


def _peek_from(dockerfile: Path) -> str | None:
    if not dockerfile.exists():
        return None
    m = _FROM_RE.search(dockerfile.read_text())
    return m.group(1) if m else None


def _pick_arrival_schedule(n: int) -> list[tuple[int, int]]:
    """Return a list of (arrive_wall_time, deadline_wall_time) pairs of length n.

    Wall-clock seconds from session start. Default: arrival every 90 s, with a
    600 s deadline window per task (see `aos_bench.scripts.generate_streams`).
    """
    out: list[tuple[int, int]] = []
    for i in range(n):
        arr = i * 90
        out.append((arr, arr + 600))
    return out


def _render_manifest(
    *,
    bundle: str,
    description: str,
    pool: str,
    base_image: str,
    extra_apt: list[str],
    tasks: list[dict],
) -> str:
    arrivals = _pick_arrival_schedule(len(tasks))
    # max_steps is the agent runtime's per-prompt LLM-call budget (independent
    # of arrival timing).
    max_steps = max(40, 12 * len(tasks))
    lines: list[str] = [
        f"# Auto-generated by generate_tb2_manifests.py — do not edit by hand.",
        f"# Bundle: {bundle} (pool={pool})",
        "",
        "[stream]",
        f'name        = "{bundle}"',
        f'description = "{description}"',
        'author      = "aos-bench task_construction"',
        "",
        "[environment]",
        "cpus              = 4",
        "memory_mb         = 8192",
        "allow_internet    = true",
        f'base_image        = "{base_image}"',
        "accept_mixed_from = true",
        "extra_apt_packages = [",
    ]
    for pkg in sorted(set(extra_apt)):
        lines.append(f'    "{pkg}",')
    lines.append("]")
    lines.append("")
    lines.append("[session]")
    lines.append(f"max_steps = {max_steps}")
    lines.append("")

    for (arr, _dl), task in zip(arrivals, tasks, strict=True):
        lines.append("[[tasks]]")
        lines.append(f'source             = "{task["source"]}"')
        lines.append(f'pool               = "{pool}"')
        lines.append(f'task_id            = "{task["task_id"]}"')
        lines.append(f"arrive_wall_time   = {arr}")
        # deadline_wall_time removed 2026-05-20
        lines.append(f'# difficulty={task["difficulty"]} category={task["category"]}')
        if task.get("from_image"):
            lines.append(f'# original FROM={task["from_image"]}')
        lines.append("")

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, default=_DEFAULT_CACHE)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "manifests",
    )
    parser.add_argument(
        "--source",
        choices=["tb2", "skillsbench"],
        default="tb2",
        help="Which source repo to scan",
    )
    parser.add_argument(
        "--max-per-bundle",
        type=int,
        default=8,
        help="Cap each generated manifest to N tasks (sorted by difficulty/easy first).",
    )
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)

    if args.source == "tb2":
        repo = args.cache_dir / "terminal-bench-2"
        bundle_label = "tb2"
    else:
        repo = args.cache_dir / "skillsbench" / "tasks"
        bundle_label = "skillsbench"

    if not repo.exists():
        raise SystemExit(f"source repo not cached: {repo} (run download_sources.py first)")

    rows: list[dict] = []
    for d in sorted(p for p in repo.iterdir() if p.is_dir()):
        info = _read_task(d)
        if info is None:
            continue
        if info["encrypted"]:
            continue  # adaptive-rejection-sampler etc.
        cat = info["category"]
        pool = CATEGORY_TO_POOL.get(cat or "")
        if not pool:
            continue
        info["pool"] = pool
        info["bundle"] = (
            f"{bundle_label}-{POOL_TO_BUNDLE.get(pool, pool).split('-', 1)[1]}"
            if "-" in POOL_TO_BUNDLE.get(pool, "")
            else f"{bundle_label}-{pool}"
        )
        info["source"] = str(d)
        rows.append(info)

    bundles: dict[str, list[dict]] = {}
    for r in rows:
        bundles.setdefault(r["bundle"], []).append(r)

    difficulty_order = {"easy": 0, "medium": 1, "hard": 2}
    for name, tasks in bundles.items():
        # Easy first so the early arrivals are quick & realistic for short streams.
        tasks.sort(key=lambda t: (difficulty_order.get(t["difficulty"] or "", 9), t["task_id"]))
        tasks = tasks[: args.max_per_bundle]
        first_pool = tasks[0]["pool"]
        body = _render_manifest(
            bundle=name,
            description=f"Auto-generated {bundle_label} stream for pool '{first_pool}'.",
            pool=first_pool,
            base_image="ubuntu:24.04",
            extra_apt=["ca-certificates", "curl", "git", "python3", "python3-pip"],
            tasks=tasks,
        )
        out_path = args.out / f"{name}.toml"
        out_path.write_text(body)
        print(f"[write] {out_path} ({len(tasks)} tasks)")

    print(f"[done] {len(bundles)} manifests under {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
